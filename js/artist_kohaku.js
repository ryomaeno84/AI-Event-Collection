function renderArtists(artists) {
  const container = document.getElementById("artist-grid");
  if (!container) return;

  container.replaceChildren();

  artists.forEach(artist => {
    const card = document.createElement("div");
    card.className = "artist-card";

    const img = document.createElement("img");
    img.src = artist.image;
    img.alt = artist.name;
    img.className = "artist-thumb";
    img.loading = "lazy";

    const info = document.createElement("div");
    info.className = "artist-info";

    const name = document.createElement("div");
    name.className = "artist-name";
    name.textContent = artist.name;

    const socials = document.createElement("div");
    socials.className = "artist-social-links";

    const links = [
      [artist.xUrl, "X (Twitter)", "x", xIcon],
      [artist.youtubeUrl, "YouTube", "youtube", ytIcon]
    ];

    for (const [url, title, type, icon] of links) {
      if (!url) continue;

      let parsed;
      try {
        parsed = new URL(url);
      } catch {
        continue;
      }

      if (!["https:", "http:"].includes(parsed.protocol)) continue;

      const a = document.createElement("a");
      a.href = parsed.href;
      a.target = "_blank";
      a.rel = "noopener noreferrer";
      a.title = title;
      a.setAttribute("aria-label", artist.name + "：" + title);
      a.className = "social-link " + type;
      a.innerHTML = icon;

      socials.appendChild(a);
    }

    info.append(name, socials);
    card.append(img, info);
    container.appendChild(card);
  });
}

